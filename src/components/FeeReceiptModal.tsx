import React, { useState } from 'react';
import { PaymentRecord, Student } from '../types/student';
import { useTheme } from '../context/ThemeContext';
import { getLibraryProfileSettings } from '../services/librarySettingsService';
import {
  downloadReceiptPdf,
  printReceiptPdf,
  formatReceiptDate,
} from '../services/receiptPdfService';
import { amountToWordsINR } from '../utils/numberToWords';
import {
  X,
  Download,
  Printer,
  Receipt,
  CheckCircle2,
  Share2,
  Building,
  Calendar,
  AlertCircle,
  Copy,
  Check,
  CreditCard,
  Banknote,
  Sparkles,
} from 'lucide-react';

interface FeeReceiptModalProps {
  record: PaymentRecord | null;
  student?: Student | null;
  isOpen: boolean;
  onClose: () => void;
  isAutoGenerated?: boolean;
}

export const FeeReceiptModal: React.FC<FeeReceiptModalProps> = ({
  record,
  student,
  isOpen,
  onClose,
  isAutoGenerated = false,
}) => {
  const { darkModeClass } = useTheme();
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);
  const [pdfError, setPdfError] = useState<string | null>(null);
  const [isPrinting, setIsPrinting] = useState(false);
  const [copiedSummary, setCopiedSummary] = useState(false);

  if (!isOpen || !record) return null;

  const settings = getLibraryProfileSettings();
  const { dateStr, timeStr } = formatReceiptDate(record.paymentDate);
  const words = amountToWordsINR(record.amountPaid);

  const studentName = record.studentName || student?.name || 'Library Student';
  const seatNumber = record.seatNumber || student?.seatNumber || 'N/A';
  const studentPhone = record.studentPhone || student?.phoneNumber || 'N/A';
  const receiptNum = record.receiptNumber || record.id;

  const handleDownload = () => {
    setPdfError(null);
    setIsGeneratingPdf(true);
    try {
      downloadReceiptPdf(record, settings, student);
      setIsGeneratingPdf(false);
    } catch (err) {
      console.error('PDF generation error:', err);
      setPdfError(err instanceof Error ? err.message : 'Failed to generate PDF receipt. Payment is safely recorded.');
      setIsGeneratingPdf(false);
    }
  };

  const handlePrint = () => {
    setPdfError(null);
    setIsPrinting(true);
    try {
      printReceiptPdf(record, settings, student);
      setTimeout(() => setIsPrinting(false), 800);
    } catch (err) {
      console.error('Print receipt error:', err);
      setPdfError(err instanceof Error ? err.message : 'Printing failed. You can still download the PDF.');
      setIsPrinting(false);
    }
  };

  const handleCopySummary = () => {
    const summary = [
      `*${settings.libraryName.toUpperCase()} - FEE RECEIPT*`,
      `Receipt No: ${receiptNum}`,
      `Date: ${dateStr} ${timeStr}`,
      `Student: ${studentName}`,
      `Seat No: ${seatNumber}`,
      `Amount Paid: INR ${record.amountPaid.toLocaleString('en-IN')}`,
      `Mode: ${record.paymentMode}`,
      record.transactionId ? `Txn Ref: ${record.transactionId}` : null,
      record.feePeriod ? `Period: ${record.feePeriod}` : null,
      `Status: Payment Confirmed (Paid in Full)`,
      `Thank you for studying with us!`,
    ]
      .filter(Boolean)
      .join('\n');

    navigator.clipboard.writeText(summary);
    setCopiedSummary(true);
    setTimeout(() => setCopiedSummary(false), 2000);
  };

  const handleShareWhatsApp = () => {
    const cleanPhone = (studentPhone || '').replace(/[^0-9]/g, '');
    const summary = [
      `*${settings.libraryName.toUpperCase()} - FEE RECEIPT*`,
      `Receipt No: ${receiptNum}`,
      `Date: ${dateStr}`,
      `Student: ${studentName}`,
      `Seat No: ${seatNumber}`,
      `Amount Paid: INR ${record.amountPaid.toLocaleString('en-IN')}`,
      `Mode: ${record.paymentMode}`,
      record.transactionId ? `Txn/Ref ID: ${record.transactionId}` : null,
      record.feePeriod ? `Fee Period: ${record.feePeriod}` : null,
      `Status: Paid in Full`,
      `Thank you for studying with us!`,
    ]
      .filter(Boolean)
      .join('\n');

    const url = cleanPhone
      ? `https://wa.me/${cleanPhone}?text=${encodeURIComponent(summary)}`
      : `https://wa.me/?text=${encodeURIComponent(summary)}`;
    window.open(url, '_blank');
  };

  return (
    <div
      className={`fixed inset-0 z-50 flex items-center justify-center p-3 sm:p-4 bg-slate-900/65 backdrop-blur-xs animate-in fade-in duration-150 ${darkModeClass}`}
      onClick={onClose}
    >
      <div
        className="bg-white rounded-3xl shadow-2xl w-full max-w-xl overflow-hidden border border-slate-200 flex flex-col max-h-[92vh] animate-in zoom-in-95 duration-200"
        onClick={(e) => e.stopPropagation()}
      >
        {/* Top Header */}
        <div className="px-6 py-4 bg-gradient-to-r from-amber-600 to-amber-700 text-white flex items-center justify-between">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-2xl bg-white/20 flex items-center justify-center shrink-0 border border-white/25">
              <Receipt className="w-5 h-5 text-white" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h3 className="text-base font-bold text-white">
                  Official Fee Receipt
                </h3>
                {isAutoGenerated && (
                  <span className="text-[10px] font-bold px-2 py-0.5 rounded-full bg-emerald-400 text-slate-950 uppercase tracking-wider flex items-center gap-1">
                    <Sparkles className="w-3 h-3" />
                    New Payment
                  </span>
                )}
              </div>
              <p className="text-xs text-amber-100 font-mono">
                {receiptNum}
              </p>
            </div>
          </div>

          <button
            type="button"
            onClick={onClose}
            className="p-1.5 text-white/80 hover:text-white rounded-full hover:bg-white/10 transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Error notification banner if PDF generation fails */}
        {pdfError && (
          <div className="mx-6 mt-4 p-3 rounded-2xl bg-rose-50 border border-rose-200 text-xs text-rose-800 flex items-start gap-2.5">
            <AlertCircle className="w-4 h-4 text-rose-600 shrink-0 mt-0.5" />
            <div className="flex-1">
              <span className="font-bold block">PDF Generation Warning:</span>
              <span>{pdfError}</span>
              <p className="text-[11px] text-rose-600 mt-1 font-medium">
                Note: Payment is safely saved in the library ledger and will never be lost.
              </p>
              <button
                type="button"
                onClick={handleDownload}
                className="mt-2 text-[11px] font-bold px-3 py-1 bg-rose-600 text-white rounded-lg hover:bg-rose-700 transition-colors"
              >
                Retry PDF Download
              </button>
            </div>
          </div>
        )}

        {/* Scrollable Receipt Preview */}
        <div className="p-6 overflow-y-auto space-y-4">
          {/* Printable Style Sheet Card */}
          <div className="bg-slate-50/80 rounded-2xl border-2 border-slate-200 p-5 space-y-4 font-sans text-slate-800">
            {/* Library Branding */}
            <div className="border-b border-slate-200 pb-3 text-center">
              <h2 className="text-base font-black text-slate-900 uppercase tracking-wider">
                {settings.libraryName}
              </h2>
              {settings.libraryAddress && (
                <p className="text-xs text-slate-500 mt-0.5">{settings.libraryAddress}</p>
              )}
              <div className="flex items-center justify-center gap-3 text-[11px] text-slate-500 mt-1">
                {settings.contactPhone && <span>Phone: {settings.contactPhone}</span>}
                {settings.contactEmail && <span>Email: {settings.contactEmail}</span>}
              </div>
            </div>

            {/* Receipt & Student Details */}
            <div className="grid grid-cols-2 gap-3 text-xs">
              <div className="space-y-1">
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Student Name</span>
                  <span className="font-bold text-slate-900 text-sm">{studentName}</span>
                </div>
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Seat / Desk</span>
                  <span className="font-mono font-bold text-amber-700 bg-amber-100/60 px-2 py-0.5 rounded text-xs inline-block">
                    Seat {seatNumber}
                  </span>
                </div>
                {studentPhone && (
                  <div>
                    <span className="text-[10px] uppercase font-bold text-slate-400 block">Mobile</span>
                    <span className="font-mono text-slate-700">{studentPhone}</span>
                  </div>
                )}
              </div>

              <div className="space-y-1 text-right">
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Receipt Number</span>
                  <span className="font-mono font-bold text-slate-900 text-xs">{receiptNum}</span>
                </div>
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Date &amp; Time</span>
                  <span className="text-slate-700 text-xs">{dateStr} &bull; {timeStr}</span>
                </div>
                <div>
                  <span className="text-[10px] uppercase font-bold text-slate-400 block">Payment Mode</span>
                  <span className="font-semibold text-slate-800 text-xs inline-flex items-center gap-1 justify-end">
                    {record.paymentMode === 'Cash' ? (
                      <Banknote className="w-3.5 h-3.5 text-emerald-600" />
                    ) : record.paymentMode === 'UPI' ? (
                      <Building className="w-3.5 h-3.5 text-indigo-600" />
                    ) : (
                      <CreditCard className="w-3.5 h-3.5 text-blue-600" />
                    )}
                    {record.paymentMode}
                  </span>
                </div>
                {record.transactionId && (
                  <div>
                    <span className="text-[10px] uppercase font-bold text-slate-400 block">Txn / Ref ID</span>
                    <span className="font-mono text-[11px] text-slate-600">{record.transactionId}</span>
                  </div>
                )}
              </div>
            </div>

            {/* Line Item Breakdown */}
            <div className="border border-slate-200 rounded-xl overflow-hidden bg-white">
              <table className="w-full text-left text-xs">
                <thead className="bg-slate-100 text-[10px] uppercase font-bold text-slate-600 border-b border-slate-200">
                  <tr>
                    <th className="py-2 px-3">Description</th>
                    <th className="py-2 px-3">Period</th>
                    <th className="py-2 px-3 text-right">Amount</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  <tr>
                    <td className="py-2.5 px-3">
                      <span className="font-bold text-slate-900 block">
                        Monthly Study Desk Fee
                      </span>
                      <span className="text-[11px] text-slate-500">
                        Reserved desk access &amp; library amenities
                      </span>
                    </td>
                    <td className="py-2.5 px-3 text-slate-600 font-mono text-[11px]">
                      {record.feePeriod || '1 Month'}
                    </td>
                    <td className="py-2.5 px-3 text-right font-mono font-bold text-slate-900">
                      ₹{record.amountPaid.toLocaleString('en-IN')}
                    </td>
                  </tr>
                </tbody>
              </table>
            </div>

            {/* Total Highlight */}
            <div className="p-3.5 rounded-xl bg-amber-500/10 border border-amber-300/80 flex items-center justify-between">
              <div>
                <span className="text-[10px] uppercase font-bold tracking-wider text-amber-800 block">
                  Total Amount Received
                </span>
                <span className="text-[11px] text-amber-900 font-medium">
                  {words}
                </span>
              </div>
              <div className="text-right">
                <span className="text-xl font-black font-mono text-amber-700">
                  ₹{record.amountPaid.toLocaleString('en-IN')}
                </span>
                <span className="text-[10px] font-bold text-emerald-700 flex items-center gap-1 justify-end mt-0.5">
                  <CheckCircle2 className="w-3 h-3 text-emerald-600" />
                  PAID IN FULL
                </span>
              </div>
            </div>

            {record.note && (
              <div className="text-xs text-slate-500 bg-white p-2.5 rounded-xl border border-slate-200">
                <span className="font-bold text-slate-700">Note: </span>
                <span className="italic">{record.note}</span>
              </div>
            )}

            {/* Footer Terms */}
            <div className="pt-2 border-t border-slate-200 flex items-end justify-between text-[10px] text-slate-400">
              <div className="max-w-[70%]">
                <p>{settings.termsAndConditions}</p>
                <p className="mt-0.5 text-slate-500 font-medium">
                  Computer-generated receipt &bull; Valid across all audits &bull; 100% offline verified
                </p>
              </div>
              <div className="text-right shrink-0">
                <div className="w-24 h-9 border-b border-dashed border-slate-400 mb-1" />
                <span className="font-bold text-slate-600 text-[10px]">Authorized Desk Seal</span>
              </div>
            </div>
          </div>
        </div>

        {/* Modal Actions */}
        <div className="px-6 py-4 bg-slate-50 border-t border-slate-200 flex items-center justify-between gap-2 flex-wrap">
          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handleShareWhatsApp}
              className="px-3 py-2 text-xs font-semibold text-emerald-800 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 rounded-xl transition-all inline-flex items-center gap-1.5"
              title="Share receipt summary on WhatsApp"
            >
              <Share2 className="w-4 h-4 text-emerald-600" />
              <span>WhatsApp</span>
            </button>

            <button
              type="button"
              onClick={handleCopySummary}
              className="px-3 py-2 text-xs font-semibold text-slate-700 bg-white hover:bg-slate-100 border border-slate-200 rounded-xl transition-all inline-flex items-center gap-1.5"
              title="Copy receipt summary text"
            >
              {copiedSummary ? (
                <>
                  <Check className="w-4 h-4 text-emerald-600" />
                  <span>Copied!</span>
                </>
              ) : (
                <>
                  <Copy className="w-4 h-4 text-slate-500" />
                  <span>Copy Text</span>
                </>
              )}
            </button>
          </div>

          <div className="flex items-center gap-2">
            <button
              type="button"
              onClick={handlePrint}
              disabled={isPrinting}
              className="px-3.5 py-2 text-xs font-semibold text-slate-800 bg-white hover:bg-slate-100 border border-slate-300 rounded-xl shadow-2xs transition-all inline-flex items-center gap-1.5"
            >
              <Printer className="w-4 h-4 text-slate-600" />
              <span>{isPrinting ? 'Opening Print...' : 'Print'}</span>
            </button>

            <button
              type="button"
              onClick={handleDownload}
              disabled={isGeneratingPdf}
              className="px-4 py-2 text-xs font-bold text-white bg-amber-600 hover:bg-amber-700 active:scale-95 rounded-xl shadow-xs transition-all inline-flex items-center gap-2"
            >
              <Download className="w-4 h-4" />
              <span>{isGeneratingPdf ? 'Generating PDF...' : 'Download PDF'}</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
